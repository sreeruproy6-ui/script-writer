import type { ProjectResult } from "../types";
import { formatSrt, formatTime, formatVtt, segmentFlags, slugify } from "./format";

export type ExportKind = "srt" | "vtt" | "dubbing" | "subtitle" | "source" | "json";

export interface ExportPayload {
  content: string;
  filename: string;
  mime: string;
  label: string;
  extension: string;
}

const LABELS: Record<ExportKind, { label: string; extension: string }> = {
  srt: { label: "Bengali subtitles", extension: "srt" },
  vtt: { label: "Web subtitles", extension: "vtt" },
  dubbing: { label: "Dubbing script", extension: "txt" },
  subtitle: { label: "Bengali subtitle text", extension: "txt" },
  source: { label: "Source transcript", extension: "txt" },
  json: { label: "Full project", extension: "json" },
};

export function buildExport(project: ProjectResult, kind: ExportKind): ExportPayload {
  const base = slugify(project.title_en || project.title_bn);
  const stem = `${base}_${kind}`;
  const generated = new Date().toISOString();
  const counts = `${project.segments.length} segments · ${(project.durationMs / 1000).toFixed(0)} seconds`;

  let content = "";
  let mime = "text/plain;charset=utf-8";

  switch (kind) {
    case "srt":
      content = project.segments
        .map(
          (segment, index) =>
            `${index + 1}\n${formatSrt(segment.start_ms)} --> ${formatSrt(segment.end_ms)}\n${segment.bengali_subtitle.trim()}`
        )
        .join("\n\n");
      break;

    case "vtt":
      content =
        "WEBVTT\n" +
        `NOTE ${project.title_en} — Bengali subtitles generated by Roy AI\n\n` +
        project.segments
          .map(
            (segment, index) =>
              `${index + 1}\n${formatVtt(segment.start_ms)} --> ${formatVtt(segment.end_ms)}\n${segment.bengali_subtitle.trim()}`
          )
          .join("\n\n");
      break;

    case "dubbing":
      content = [
        "ROY AI — BENGALI DUBBING SCRIPT",
        "==============================================",
        `Title:      ${project.title_bn} (${project.title_en})`,
        `Source:     ${project.sourceLanguage}  →  Bengali (bn-BD)`,
        `Media file: ${project.fileName}`,
        `Runtime:    ${formatTime(project.durationMs)} · ${counts}`,
        `Generated:  ${generated}`,
        "",
        "PERFORMANCE NOTES",
        "· Respect the in/out timecodes; keep breaths inside the window.",
        "· SFX cues are editorial and should not be voiced unless marked.",
        "· Character spellings follow the approved glossary.",
        "",
        "----------------------------------------------",
        "",
        ...project.segments.map((segment) => {
          const lines = [
            `[${formatTime(segment.start_ms)} – ${formatTime(segment.end_ms)}]  ${segment.speaker}  (${segment.tone || "Neutral"})`,
            segment.bengali_dubbing.trim(),
          ];
          if (segment.sfx) lines.push(`SFX: ${segment.sfx}`);
          if (segment.review_note && segment.review_note !== "Clean") {
            lines.push(`NOTE: ${segment.review_note}`);
          }
          return `${lines.join("\n")}\n`;
        }),
      ].join("\n");
      break;

    case "subtitle":
      content = project.segments.map((segment) => segment.bengali_subtitle.trim()).join("\n");
      break;

    case "source":
      content = project.segments
        .map(
          (segment) =>
            `[${formatTime(segment.start_ms)} – ${formatTime(segment.end_ms)}] ${segment.speaker}\n${segment.source_text.trim()}`
        )
        .join("\n\n");
      break;

    case "json":
      content = JSON.stringify(
        {
          schema: "roy-ai.project.v1",
          id: project.id,
          status: project.status,
          created_at: new Date(project.createdAt).toISOString(),
          exported_at: generated,
          title_bn: project.title_bn,
          title_en: project.title_en,
          summary_bn: project.summary_bn,
          source_language: project.sourceLanguage,
          target_language: project.targetLanguage,
          content_type: project.contentType,
          detected_languages: project.detected_languages,
          media: {
            file_name: project.fileName,
            file_size: project.fileSize,
            file_type: project.fileType,
            duration_ms: project.durationMs,
          },
          glossary: project.glossary,
          segments: project.segments,
        },
        null,
        2
      );
      mime = "application/json;charset=utf-8";
      break;

    default:
      break;
  }

  return {
    content,
    filename: `${stem}.${LABELS[kind].extension}`,
    mime,
    label: LABELS[kind].label,
    extension: LABELS[kind].extension,
  };
}

export function downloadExport(project: ProjectResult, kind: ExportKind): ExportPayload {
  const payload = buildExport(project, kind);
  const prefix = kind === "json" ? "" : "\ufeff";
  const blob = new Blob([prefix + payload.content], { type: payload.mime });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement("a");
  anchor.href = url;
  anchor.download = payload.filename;
  document.body.appendChild(anchor);
  anchor.click();
  anchor.remove();
  window.setTimeout(() => URL.revokeObjectURL(url), 1200);
  return payload;
}

export async function shareExport(project: ProjectResult, kind: ExportKind): Promise<boolean> {
  const payload = buildExport(project, kind);
  const prefix = kind === "json" ? "" : "\ufeff";
  const file = new File([prefix + payload.content], payload.filename, { type: payload.mime });

  if (typeof navigator.share === "function" && navigator.canShare?.({ files: [file] })) {
    try {
      await navigator.share({
        files: [file],
        title: `${project.title_bn} · Roy AI`,
        text: "Bengali localization assets from Roy AI Studio.",
      });
      return true;
    } catch (error) {
      const err = error as DOMException;
      if (err?.name === "AbortError") return false;
    }
  }

  downloadExport(project, kind);
  return false;
}

export async function copyToClipboard(text: string): Promise<boolean> {
  try {
    if (navigator.clipboard?.writeText) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch {
    // Continue to the legacy fallback.
  }
  try {
    const area = document.createElement("textarea");
    area.value = text;
    area.style.position = "fixed";
    area.style.opacity = "0";
    document.body.appendChild(area);
    area.select();
    const ok = document.execCommand("copy");
    area.remove();
    return ok;
  } catch {
    return false;
  }
}

export function exportReadiness(project: ProjectResult): number {
  if (!project.segments.length) return 0;
  const flagged = project.segments.filter((segment) => segmentFlags(segment).length > 0).length;
  return Math.round(((project.segments.length - flagged) / project.segments.length) * 100);
}
